/**
 * Comprehensive Dataset of Grid Measurement Stations & City Profiles in Poland
 * Includes:
 * - GPZ (Główne Punkty Zasilania 110/15kV & SE 400/220/110kV)
 * - Renewable Telemetry Stations (Offshore/Onshore Wind & Large-Scale PV)
 * - Environmental & Air Quality Monitoring Stations (GIOŚ / IMGW)
 * - BESS (Battery Energy Storage Systems)
 * - City Profiles / Urban Grid Nodes ("strój miast")
 * - High-Voltage Transmission Line Interconnectors
 */

export interface MeasurementStation {
  id: string;
  name: string;
  category: 'gpz' | 'renewable' | 'environmental' | 'bess';
  voltageLevel: string; // e.g. "400/110 kV", "110/15 kV", "15 kV"
  city: string;
  voivodeship: string;
  position: [number, number]; // [lat, lng]
  status: 'operational' | 'warning' | 'error';
  lastTelemetry: {
    voltageKv: number;
    currentA: number;
    activePowerMw: number;
    reactivePowerMvar: number;
    frequencyHz: number;
    transformerLoadingPct: number;
    temperatureC: number;
    cosPhi: number;
    thdPct: number;
    environmental?: {
      pm25?: number;
      pm10?: number;
      co2Ppm?: number;
      noiseDb?: number;
    };
  };
}

export interface CityGridProfile {
  id: string;
  name: string;
  voivodeship: string;
  position: [number, number];
  role:
    | 'Metropolia krajowa'
    | 'Węzeł regionalny'
    | 'Ośrodek przemysłowy'
    | 'Hub portowy i offshore';
  peakDemandMw: number;
  currentDemandMw: number;
  renewableGenerationMw: number;
  substationsCount: number;
  gridLoadPct: number;
  primaryVoltageKv: number;
  distributionVoltageKv: number;
  reliabilitySaidiMin: number;
  bessCapacityMwh: number;
  sensorsSummary: {
    temp: number;
    airQualityIndex: 'Bardzo dobra' | 'Dobra' | 'Umiarkowana' | 'Dostateczna';
    co2Ppm: number;
  };
}

